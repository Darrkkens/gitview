// Diagnostic kinds, classified from the compiler's own wording.
const (
	DiagEscapes    = "escapes to heap"
	DiagMoved      = "moved to heap"
	DiagNoEscape   = "does not escape"
	DiagLeaking    = "leaking param"
	DiagCanInline  = "can inline"
	DiagCannot     = "cannot inline"
	DiagInlineCall = "inlining call"
	DiagDevirt     = "devirtualized"
	DiagOther      = "other"
)

// Diagnostic is one message printed by `go build -gcflags=-m=2`, verbatim.
type Diagnostic struct {
	File    string   `json:"file"`
	Line    int      `json:"line"`
	Col     int      `json:"col"`
	Kind    string   `json:"kind"`
	Message string   `json:"message"`
	Flow    []string `json:"flow,omitempty"` // the compiler's explanation lines (-m=2)
	Symbol  string   `json:"symbol,omitempty"`
	Func    string   `json:"func,omitempty"`
}

type EscapeReport struct {
	Packages []string            `json:"packages"`
	Diags    []Diagnostic        `json:"diagnostics"`
	Errors   []string            `json:"errors,omitempty"` // build errors
	Artifact evidence.Artifact   `json:"artifact"`
	Evidence []evidence.Evidence `json:"evidence"`
}

var diagLine = regexp.MustCompile(`^(.+?\.go):(\d+):(\d+): (.*)$`)

func classify(msg string) string {
	switch {
	case strings.HasPrefix(msg, "moved to heap:"):
		return DiagMoved
	case strings.Contains(msg, "escapes to heap"):
		return DiagEscapes
	case strings.HasSuffix(msg, "does not escape"):
		return DiagNoEscape
	case strings.HasPrefix(msg, "leaking param"):
		return DiagLeaking
	case strings.HasPrefix(msg, "can inline"):
		return DiagCanInline
	case strings.HasPrefix(msg, "cannot inline"):
		return DiagCannot
	case strings.HasPrefix(msg, "inlining call to"):
		return DiagInlineCall
	case strings.HasPrefix(msg, "devirtualizing") || strings.Contains(msg, "devirtualized"):
		return DiagDevirt
	}
	return DiagOther
}

// ParseEscape reads compiler output. Lines indented after a diagnostic
// (the -m=2 "flow:" explanations) are attached to it unchanged.
func ParseEscape(out []byte, progs []*flow.Program) *EscapeReport {
	r := &EscapeReport{}
	m := newMapper(progs)
	sc := bufio.NewScanner(bytes.NewReader(out))
	sc.Buffer(make([]byte, 64*1024), 4<<20)
	seenPkg := map[string]bool{}
	for sc.Scan() {
		line := sc.Text()
		if pkg, ok := strings.CutPrefix(line, "# "); ok {
			if !seenPkg[pkg] {
				seenPkg[pkg] = true
				r.Packages = append(r.Packages, pkg)
			}
			continue
		}
		if strings.HasPrefix(line, "<autogenerated>") {
			continue // compiler-generated wrappers have no source location
		}
		mm := diagLine.FindStringSubmatch(line)
		if mm == nil {
			if strings.TrimSpace(line) != "" {
				r.Errors = append(r.Errors, line)
			}
			continue
		}
		msg := mm[4]
		ln, _ := strconv.Atoi(mm[2])
		col, _ := strconv.Atoi(mm[3])
		file := m.rel(mm[1])
		if strings.HasPrefix(msg, " ") {
			// Explanation of the previous diagnostic at the same position.
			if n := len(r.Diags); n > 0 && r.Diags[n-1].File == file && r.Diags[n-1].Line == ln {
				r.Diags[n-1].Flow = append(r.Diags[n-1].Flow, strings.TrimSpace(msg))
			}
			continue
		}
		d := Diagnostic{File: file, Line: ln, Col: col, Kind: classify(msg), Message: strings.TrimSuffix(msg, ":")}
		if dup := duplicateOf(r.Diags, d); dup >= 0 {
			continue // -m=2 prints the explained form, then the plain summary
		}
		if d.Kind == DiagMoved {
			// "moved to heap: x" follows "x escapes to heap" for the same
			// variable: one fact, kept as the more specific message.
			name := strings.TrimSpace(strings.TrimPrefix(d.Message, "moved to heap:"))
			if n := len(r.Diags); n > 0 {
				prev := &r.Diags[n-1]
				if prev.File == d.File && prev.Line == d.Line && prev.Kind == DiagEscapes && strings.HasPrefix(prev.Message, name+" escapes to heap") {
					prev.Kind, prev.Message = DiagMoved, d.Message
					continue
				}
			}
		}
		if strings.Contains(msg, ": ") && d.Kind == DiagOther && strings.Contains(strings.ToLower(msg), "error") {
			r.Errors = append(r.Errors, line)
			continue
		}
		for _, p := range progs {
			if fn := p.FuncAt(file, ln); fn != nil {
				d.Symbol, d.Func = flow.Origin(fn).String(), flow.ShortName(fn)
				break
			}
		}
		r.Diags = append(r.Diags, d)
	}
	sort.SliceStable(r.Diags, func(i, j int) bool {
		if r.Diags[i].File != r.Diags[j].File {
			return r.Diags[i].File < r.Diags[j].File
		}
		if r.Diags[i].Line != r.Diags[j].Line {
			return r.Diags[i].Line < r.Diags[j].Line
		}
		return r.Diags[i].Col < r.Diags[j].Col
	})
	r.Evidence = []evidence.Evidence{{Kind: evidence.Compiler, Basis: evidence.BasisStatic, Source: "go build -gcflags=-m=2",
		Details: "escape-analysis and inlining decisions printed by the compiler for this build, reported verbatim"}}
	return r
}

// duplicateOf finds an earlier diagnostic at the same position saying the
// same thing ("x escapes to heap in F" and "x escapes to heap").
func duplicateOf(ds []Diagnostic, d Diagnostic) int {
	for i := len(ds) - 1; i >= 0 && i >= len(ds)-8; i-- {
		o := ds[i]
		if o.File == d.File && o.Line == d.Line && o.Col == d.Col && o.Kind == d.Kind &&
			(strings.HasPrefix(o.Message, d.Message) || strings.HasPrefix(d.Message, o.Message)) {
			return i
		}
	}
	return -1
}

// BuildFailed moves unclassified messages to Errors: when the build failed
// they are compiler errors, not diagnostics.
func (r *EscapeReport) BuildFailed() {
	var keep []Diagnostic
	for _, d := range r.Diags {
		if d.Kind == DiagOther {
			r.Errors = append(r.Errors, fmt.Sprintf("%s:%d:%d: %s", d.File, d.Line, d.Col, d.Message))
			continue
		}
		keep = append(keep, d)
	}
	r.Diags = keep
}

// ForSymbol returns the diagnostics located in a module function.
func (r *EscapeReport) ForSymbol(id string) []Diagnostic {
	var out []Diagnostic
	for _, d := range r.Diags {
		if d.Symbol == id {
			out = append(out, d)
		}
	}
	return out
}

// Counts summarises diagnostics by kind.
func (r *EscapeReport) Counts() map[string]int {
	c := map[string]int{}
	for _, d := range r.Diags {
		c[d.Kind]++
	}
	return c
}

// EscapeSpec builds the command printing compiler diagnostics for pkg. The
// binary is discarded (-o /dev/null), so nothing is written to the module.
func EscapeSpec(moduleDir, pkg string) run.Spec {
	return run.Spec{Args: []string{"go", "build", "-gcflags=-m=2", "-o", os.DevNull, pkg}, Dir: moduleDir}
}

// BenchOptions configure a benchmark capture.
type BenchOptions struct {
	Bench     string // -bench regexp (default ".")
	Count     int    // -count (default 6, enough for a significance test)
	Benchtime string // -benchtime, optional
	Profiles  bool   // also write CPU and memory profiles
	OutDir    string // where results go (outside the repository)
}

// BenchFiles are the files a capture produces.
type BenchFiles struct {
	Output, CPU, Mem, Binary string
}

// BenchSpec builds the go test command for benchmarks of one package. The
// test binary and the profiles are written to OutDir, never to the module.
func BenchSpec(moduleDir, pkg string, opt BenchOptions) (run.Spec, BenchFiles) {
	if opt.Bench == "" {
		opt.Bench = "."
	}
	if opt.Count <= 0 {
		opt.Count = 6
	}
	f := BenchFiles{Output: filepath.Join(opt.OutDir, "bench.txt")}
	args := []string{"go", "test", "-run=^$", "-bench=" + opt.Bench, "-benchmem", "-count=" + strconv.Itoa(opt.Count)}
	if opt.Benchtime != "" {
		args = append(args, "-benchtime="+opt.Benchtime)
	}
	if opt.Profiles {
		f.CPU = filepath.Join(opt.OutDir, "cpu.pprof")
		f.Mem = filepath.Join(opt.OutDir, "mem.pprof")
		f.Binary = filepath.Join(opt.OutDir, "bench.test")
		args = append(args, "-cpuprofile="+f.CPU, "-memprofile="+f.Mem, "-o", f.Binary)
	}
	args = append(args, pkg)
	return run.Spec{Args: args, Dir: moduleDir}, f
}
