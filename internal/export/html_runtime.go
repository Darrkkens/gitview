// RuntimeHTML writes the standalone report of a runtime capture: a single
// offline file (no network access) whose only script is pinned by the
// Content-Security-Policy. a is the capture; cmp, when given, compares it
// with an earlier capture (a is then the comparison's B).
func RuntimeHTML(w io.Writer, a *report.Analysis, cmp *report.Comparison) error {
	payload := struct {
		A          *report.Analysis   `json:"a"`
		Base       *report.Analysis   `json:"base,omitempty"`
		Comparison *report.Comparison `json:"comparison,omitempty"`
		Generated  time.Time          `json:"generated"`
	}{A: slim(a), Comparison: cmp, Generated: time.Now()}
	if cmp != nil {
		payload.Base = slim(cmp.A)
	}
	data, err := json.Marshal(payload)
	if err != nil {
		return err
	}
	title := "Runtime Performance · " + a.ID
	if a.Label != "" {
		title = "Runtime Performance · " + a.Label
	}
	if cmp != nil {
		title = "Runtime comparison · " + cmp.AID + " → " + cmp.BID
	}
	var buf bytes.Buffer
	err = runtimeTmpl.Execute(&buf, struct {
		Title string
		CSP   string
		Style template.CSS
		JS    template.JS
		Data  template.JS
	}{title, runtimeCSP, template.CSS(runtimeCSS), template.JS(runtimeJS), template.JS(data)})
	if err != nil {
		return err
	}
	_, err = w.Write(buf.Bytes())
	return err
}

// slim drops the parts of the profile reports the page does not show
// (per-line statistics, call edges), without modifying a.
func slim(a *report.Analysis) *report.Analysis {
	if a == nil || a.Profiles == nil {
		return a
	}
	c := *a
	p := *a.Profiles
	for _, r := range []**perf.Report{&p.CPU, &p.Allocs, &p.Inuse, &p.Mutex, &p.Block, &p.Goroutines} {
		if *r != nil {
			x := **r
			x.Lines, x.Edges, x.Evidence = nil, nil, nil
			*r = &x
		}
	}
	c.Profiles = &p
	return &c
}

